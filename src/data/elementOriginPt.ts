export const locationPt = (s: string | null) =>
  s ? s.split('/').map((p) => LOCATION_PT[p.trim()] ?? p.trim()).join(' / ') : s;

/** Traduções de termos que aparecem na lista de descobridores. */
export function discoverersPt(s: string | null): string | null {
  if (!s) return s;
  return s.replace(/, et al\.?/g, ' e colaboradores').replace(/\bet al\.?/g, 'e colaboradores').replace(/\band\b/g, 'e').replace(/U of Calif/g, 'Universidade da Califórnia');
}
